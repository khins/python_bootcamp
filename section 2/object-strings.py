'''
1. Strings

A string (str) is Python’s object for storing text. It consists of zero or more characters, including letters, numbers, spaces, punctuation, symbols, and Unicode characters.

2. String Literals

A literal is syntax in your code that directly creates an object. For example:
'''
"sushi"
'sushi' # literal   
print('hello')

'''
3. Strings Are Sequences

The technical definition introduced in the lesson is:

A string is an immutable sequence of text characters.

4. Strings Are Immutable

Immutable means a string cannot be changed in place after it has been created.

5. Quotes Inside Strings

If your text contains an apostrophe, double quotes are convenient:
"You're right"

6. Spaces and Empty Strings

A space is itself a character:
" "

7. "5" Is Not the Same as 5

This is an especially important Python concept:

"5"     # string
5       # number

8. Triple-Quoted Strings

Python also supports triple quotes:
"""
Hello
My name is Kevin.
I'm learning Python.
"""

Bootcamp Takeaways

The main concepts worth committing to memory from this lesson are:

Everything in Python is an object.

String = text data
String type = str

"hello"  → string
'hello'  → string
"5"      → string
5        → number

""       → empty string (0 characters)
" "      → string containing 1 space

Strings are ordered sequences.
Strings are immutable.

Single quotes  → 'Python'
Double quotes  → "Python"
Triple quotes  → multi-line strings
'''